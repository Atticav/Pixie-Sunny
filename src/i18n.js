const ATTRIBUTE_NAMES = ['placeholder', 'title', 'aria-label'];

export const translateUserFacingText = (value) => {
  if (typeof value !== 'string') return value;
  const exact = EXACT_TEXT.get(value.trim());
  if (exact) return exact;
  let translated = value;
  for (const [pattern, replacement] of REGEX_REPLACEMENTS) {
    translated = translated.replace(pattern, replacement);
  }
  return translated;
};

const localizeTextNode = (node) => {
  const original = node.nodeValue;
  if (!original || !original.trim()) return;
  const translated = translateUserFacingText(original);
  if (translated !== original) node.nodeValue = translated;
};

export const localizeDom = (root = document.body) => {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    localizeTextNode(node);
    node = walker.nextNode();
  }

  const elements = root.querySelectorAll ? root.querySelectorAll('*') : [];
  elements.forEach((element) => {
    if (element.childElementCount === 0) {
      const textContent = element.textContent;
      if (textContent && textContent.trim()) {
        const translated = translateUserFacingText(textContent.trim());
        if (translated !== textContent.trim()) {
          element.textContent = translated;
        }
      }
    }
    ATTRIBUTE_NAMES.forEach((attribute) => {
      const current = element.getAttribute(attribute);
      if (!current) return;
      const translated = translateUserFacingText(current);
      if (translated !== current) element.setAttribute(attribute, translated);
    });
  });
};

export const installEnglishUi = () => {
  if (typeof document === 'undefined' || typeof window === 'undefined') return;
  document.documentElement.lang = 'en';
  document.title = translateUserFacingText(document.title);
  localizeDom(document.body);

  const nativeAlert = window.alert?.bind(window);
  const nativeConfirm = window.confirm?.bind(window);
  if (nativeAlert) window.alert = (message) => nativeAlert(translateUserFacingText(String(message)));
  if (nativeConfirm) window.confirm = (message) => nativeConfirm(translateUserFacingText(String(message)));

  const observer = new MutationObserver((mutations) => {
    mutations.forEach((mutation) => {
      if (mutation.type === 'characterData' && mutation.target) {
        localizeTextNode(mutation.target);
      }
      mutation.addedNodes.forEach((node) => {
        if (node.nodeType === Node.TEXT_NODE) {
          localizeTextNode(node);
        } else if (node.nodeType === Node.ELEMENT_NODE) {
          localizeDom(node);
        }
      });
    });
  });
  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
};
